/// English word (lowercase) → Japanese gloss, for the hover dictionary.
///
/// Built from the word questions plus the glossary of supporting vocabulary, then expanded so that
/// every inflected form appearing in a question ("studies", "running") is a key in its own right.
/// That keeps the frontend to a plain lookup.
/// Dictionary keys that are idioms, so the hover can say "慣用句なら" before their meaning. An idiom
/// can also be read word for word: "The cat is under the table" is about a cat, not about
/// something done secretly. A compound in the vocabulary ("doggy bag", "job security") has no
/// such second reading and is left out, even when an idiom question happens to share it.
pub fn idiom_keys(conn: &Connection) -> rusqlite::Result<Vec<String>> {
    let mut stmt = conn.prepare(
        "SELECT DISTINCT lower(en) FROM questions WHERE kind = 'idiom'
           AND lower(en) NOT IN (SELECT lower(en) FROM questions WHERE kind = 'word')
         ORDER BY 1",
    )?;
    let rows = stmt.query_map([], |r| r.get(0))?;
    rows.collect()
}

pub fn dictionary(conn: &Connection) -> rusqlite::Result<HashMap<String, String>> {
    let mut map: HashMap<String, String> =
        serde_json::from_str(GLOSSARY_JSON).expect("data/glossary.json must be a valid JSON object");

    {
        // Vocabulary and idioms both go in under their whole English. A multi-word entry stays a
        // phrase: "doggy bag" means 持ち帰り用の袋, but "doggy" on its own does not, so the words
        // inside it are never given the phrase's meaning. The frontend finds phrases in a sentence
        // and shows their meaning alongside each word's own.
        let mut stmt = conn.prepare("SELECT en, ja FROM questions WHERE kind IN ('word', 'idiom') ORDER BY id")?;
        let rows = stmt.query_map([], |r| Ok((r.get::<_, String>(0)?, r.get::<_, String>(1)?)))?;
        let mut asked: HashMap<String, Vec<String>> = HashMap::new();
        for row in rows {
            let (en, ja) = row?;
            let senses = asked.entry(en.to_lowercase()).or_default();
            for s in ja.split('、') {
                if !senses.iter().any(|x| x == s) {
                    senses.push(s.to_string());
                }
            }
        }
        // Question data comes first: it is the vocabulary being studied. A word asked in two senses
        // (right: 右 / 正しい) keeps both, and senses only the glossary has (like: 〜のような) follow,
        // so a word in a sentence shows every meaning it may have there.
        for (key, mut senses) in asked {
            if let Some(extra) = map.get(&key) {
                for s in extra.split('、') {
                    if !senses.iter().any(|x| x == s) {
                        senses.push(s.to_string());
                    }
                }
            }
            map.insert(key, senses.join("、"));
        }
    }

    let texts: Vec<String> = {
        let mut stmt = conn
            .prepare("SELECT en, COALESCE(prompt, ''), COALESCE(choices, ''), COALESCE(example, '') FROM questions")?;
        let rows = stmt.query_map([], |r| {
            Ok(format!(
                "{} {} {} {}",
                r.get::<_, String>(0)?,
                r.get::<_, String>(1)?,
                r.get::<_, String>(2)?,
                r.get::<_, String>(3)?
            ))
        })?;
        rows.collect::<Result<_, _>>()?
    };
    let mut derived: HashMap<String, String> = HashMap::new();
    for text in &texts {
        for word in crate::util::tokens(text) {
            if map.contains_key(&word) || derived.contains_key(&word) {
                continue;
            }
            if let Some(gloss) = crate::util::lemmas(&word).iter().find_map(|l| map.get(l)) {
                derived.insert(word, gloss.clone());
            }
        }
    }
    map.extend(derived);
    Ok(map)
}

