/// Question key → part of speech, for every word question.
pub fn word_pos() -> &'static HashMap<String, String> {
    static TABLE: std::sync::OnceLock<HashMap<String, String>> = std::sync::OnceLock::new();
    TABLE.get_or_init(|| serde_json::from_str(WORD_POS_JSON).expect("data/word-pos.json must be a valid JSON object"))
}

/// English (lowercase) → the other words of every set in word-confusables.json it belongs to.
pub fn confusables() -> &'static HashMap<String, Vec<String>> {
    static TABLE: std::sync::OnceLock<HashMap<String, Vec<String>>> = std::sync::OnceLock::new();
    TABLE.get_or_init(|| {
        let sets: Vec<Vec<String>> =
            serde_json::from_str(WORD_CONFUSABLES_JSON).expect("data/word-confusables.json must be a JSON array of arrays");
        let mut out: HashMap<String, Vec<String>> = HashMap::new();
        for set in sets {
            let set: Vec<String> = set.iter().map(|w| w.to_lowercase()).collect();
            for w in &set {
                let others = out.entry(w.clone()).or_default();
                for o in &set {
                    if o != w && !others.contains(o) {
                        others.push(o.clone());
                    }
                }
            }
        }
        out
    })
}

fn tier_overrides() -> &'static HashMap<String, String> {
    static TABLE: std::sync::OnceLock<HashMap<String, String>> = std::sync::OnceLock::new();
    TABLE.get_or_init(|| serde_json::from_str(TIERS_JSON).expect("data/tiers.json must be a valid JSON object"))
}

/// The home screen's tab for a question: 英単語 / 複合語 / 文法 / 慣用句 / フレーズ / 例文. A word
/// question of several words, or of words joined by a hyphen, is a compound (average deviation,
/// ex-boyfriend).
pub fn tier_of(kind: &str, key: &str, en: &str) -> String {
    if let Some(t) = tier_overrides().get(key) {
        return t.clone();
    }
    match kind {
        // A verb of two words or more (get up, look forward to) is still a verb to learn as one: it
        // goes with the single words, under 動詞.
        "word" if en.contains([' ', '-']) && word_pos().get(key).map(String::as_str) != Some("verb") => "compound",
        "word" => "word",
        "grammar" => "grammar",
        "idiom" => "idiom",
        // Conversation: the listening replies and the phrases to learn by heart.
        "dialogue" | "expression" => "phrase",
        _ => "example",
    }
    .to_string()
}

